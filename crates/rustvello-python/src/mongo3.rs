// ─── Trigger Store ─────────────────────────────────────────────

#[pyclass(name = "RustMongo3TriggerStore")]
pub struct PyMongo3TriggerStore {
    pub(crate) store: Arc<Mongo3TriggerStore>,
    pub(crate) manager: TriggerManager,
}

#[pymethods]
impl PyMongo3TriggerStore {
    #[new]
    fn new(pool: &PyMongo3Pool) -> Self {
        let store = Arc::new(Mongo3TriggerStore::new(Arc::clone(&pool.inner)));
        let manager = TriggerManager::new(Arc::clone(&store) as Arc<dyn TriggerStore>);
        Self { store, manager }
    }
}

impl_py_trigger_store!(PyMongo3TriggerStore);

// ─── Client Data Store ─────────────────────────────────────────

#[pyclass(name = "RustMongo3ClientDataStore")]
pub struct PyMongo3ClientDataStore {
    pub(crate) inner: Arc<ClientDataStoreManager>,
}

#[pymethods]
impl PyMongo3ClientDataStore {
    #[new]
    #[pyo3(signature = (pool, min_size_to_cache=1024, max_size_to_cache=0, local_cache_size=128))]
    fn new(
        pool: &PyMongo3Pool,
        min_size_to_cache: usize,
        max_size_to_cache: usize,
        local_cache_size: usize,
    ) -> Self {
        let backend: Arc<dyn ClientDataStore> =
            Arc::new(Mongo3ClientDataStore::new(Arc::clone(&pool.inner)));
        let mut config = ClientDataStoreConfig::default();
        config.min_size_to_cache = min_size_to_cache;
        config.max_size_to_cache = max_size_to_cache;
        config.local_cache_size = local_cache_size;
        let manager = ClientDataStoreManager::new(backend, config);
        Self {
            inner: Arc::new(manager),
        }
    }
}

impl_py_client_data_store!(PyMongo3ClientDataStore);

