//! PyO3 wrappers for MongoDB 3.6+ backend components.

use pyo3::prelude::*;
use std::sync::Arc;

use rustvello_core::client_data_store::{ClientDataStore, ClientDataStoreManager};
use rustvello_core::trigger::{TriggerManager, TriggerStore};
use rustvello_mongo3::prelude::*;
use rustvello_proto::config::ClientDataStoreConfig;

// ─── Connection Pool ───────────────────────────────────────────

/// Shared MongoDB 3.6+ connection pool for reuse across components.
#[pyclass(name = "RustMongo3Pool")]
pub struct PyMongo3Pool {
    pub(crate) inner: Arc<MongoPool>,
}

#[pymethods]
impl PyMongo3Pool {
    /// Create a new MongoDB pool from a connection URI, database name, and app ID.
    ///
    /// The effective database name is `{db_name}_{app_id}`, providing
    /// per-application isolation when multiple apps share the same cluster.
    #[new]
    fn new(uri: &str, db_name: &str, app_id: &str) -> Self {
        Self {
            inner: Arc::new(MongoPool::new(uri, db_name, app_id)),
        }
    }
}

// ─── Broker ────────────────────────────────────────────────────

#[pyclass(name = "RustMongo3Broker")]
pub struct PyMongo3Broker {
    pub(crate) inner: Arc<Mongo3Broker>,
}

#[pymethods]
impl PyMongo3Broker {
    #[new]
    fn new(pool: &PyMongo3Pool) -> Self {
        Self {
            inner: Arc::new(Mongo3Broker::new(Arc::clone(&pool.inner))),
        }
    }
}

impl_py_broker!(PyMongo3Broker);

