// ─── Trigger Store ─────────────────────────────────────────────

#[pyclass(name = "RustPostgresTriggerStore")]
pub struct PyPostgresTriggerStore {
    pub(crate) store: Arc<PostgresTriggerStore>,
    pub(crate) manager: TriggerManager,
}

#[pymethods]
impl PyPostgresTriggerStore {
    #[new]
    fn new(db: &PyPostgresDatabase) -> Self {
        let store = Arc::new(PostgresTriggerStore::new(Arc::clone(&db.inner)));
        let manager = TriggerManager::new(Arc::clone(&store) as Arc<dyn TriggerStore>);
        Self { store, manager }
    }
}

impl_py_trigger_store!(PyPostgresTriggerStore);

// ─── Client Data Store ─────────────────────────────────────────

#[pyclass(name = "RustPostgresClientDataStore")]
pub struct PyPostgresClientDataStore {
    pub(crate) inner: Arc<ClientDataStoreManager>,
}

#[pymethods]
impl PyPostgresClientDataStore {
    #[new]
    #[pyo3(signature = (db, min_size_to_cache=1024, max_size_to_cache=0, local_cache_size=128))]
    fn new(
        db: &PyPostgresDatabase,
        min_size_to_cache: usize,
        max_size_to_cache: usize,
        local_cache_size: usize,
    ) -> Self {
        let backend: Arc<dyn ClientDataStore> =
            Arc::new(PostgresClientDataStore::new(Arc::clone(&db.inner)));
        let mut config = ClientDataStoreConfig::default();
        config.min_size_to_cache = min_size_to_cache;
        config.max_size_to_cache = max_size_to_cache;
        config.local_cache_size = local_cache_size;
        let manager = ClientDataStoreManager::new(backend, config);
        Self {
            inner: Arc::new(manager),
        }
    }
}

impl_py_client_data_store!(PyPostgresClientDataStore);

