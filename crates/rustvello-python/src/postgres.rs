//! PyO3 wrappers for PostgreSQL backend components.

use pyo3::prelude::*;
use std::sync::Arc;

use rustvello_core::client_data_store::{ClientDataStore, ClientDataStoreManager};
use rustvello_core::trigger::{TriggerManager, TriggerStore};
use rustvello_postgres::db::Database;
use rustvello_postgres::prelude::*;
use rustvello_proto::config::ClientDataStoreConfig;

use crate::error::to_py_err;

// ─── Database Connection ───────────────────────────────────────

/// Shared PostgreSQL connection pool for reuse across components.
#[pyclass(name = "RustPostgresDatabase")]
pub struct PyPostgresDatabase {
    pub(crate) inner: Arc<Database>,
}

#[pymethods]
impl PyPostgresDatabase {
    /// Connect to a PostgreSQL database using a connection string.
    ///
    /// The `app_id` creates a dedicated schema for per-application isolation.
    #[new]
    fn new(connection_string: &str, app_id: &str) -> PyResult<Self> {
        let db = crate::runtime::shared_runtime()?
            .block_on(Database::connect(connection_string, app_id))
            .map_err(to_py_err)?;
        Ok(Self {
            inner: Arc::new(db),
        })
    }
}

// ─── Broker ────────────────────────────────────────────────────

#[pyclass(name = "RustPostgresBroker")]
pub struct PyPostgresBroker {
    pub(crate) inner: Arc<PostgresBroker>,
}

#[pymethods]
impl PyPostgresBroker {
    #[new]
    fn new(db: &PyPostgresDatabase) -> Self {
        Self {
            inner: Arc::new(PostgresBroker::new(Arc::clone(&db.inner))),
        }
    }
}

impl_py_broker!(PyPostgresBroker);

